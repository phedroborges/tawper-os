const PROBLEM_MARKS = new Set([
  "errou",
  "usuario_marcou_erro",
  "modelo_caiu",
  "comprovante_inventado",
  "limite_passos",
]);

export function isProblemMark(mark: string): boolean {
  return (
    PROBLEM_MARKS.has(mark) ||
    mark.startsWith("excecao:") ||
    mark.startsWith("recusado:")
  );
}

export function isDisconnectionMark(mark: string): boolean {
  return (
    mark === "modelo_caiu" ||
    mark.startsWith("excecao:") ||
    mark.includes("timeout") ||
    mark.includes("429")
  );
}

/**
 * Avalia a qualidade do pedido enviado pelo vendedor no WhatsApp.
 * Não adianta culpar a IA quando o vendedor manda um relato vago sem cliente, sem resultado ou sem próximo passo.
 */
export function evaluateSellerOrderQuality(input: {
  question: string;
  hasCompanyId?: boolean;
  gravou?: string[];
  marcas?: string[];
  resposta?: string;
}): OrderQualityEvaluation {
  const q = (input.question ?? "").trim();
  const lower = q
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
  const gravou = input.gravou ?? [];
  const marcas = input.marcas ?? [];
  const respLower = (input.resposta ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();

  // Comandos curtos de controle ("confirmar", "ok", "errou", "desfazer") ou simples consulta de agenda
  const isControlCmd = /^(confirmar|confirmo|cancelar|desfazer|errou|ta errado|esta errado|ok|obrigado|valeu|bom dia|boa tarde)$/i.test(
    lower.replace(/[^a-z0-9 ]/g, "").trim(),
  );
  if (isControlCmd) {
    return {
      score: 100,
      grade: "completo",
      hasClient: true,
      hasOutcome: true,
      hasNextStep: true,
      missing: [],
      feedback: "Comando de confirmação/controle direto.",
    };
  }

  const isConsultOnly =
    gravou.includes("consultar_crm") ||
    (gravou.length === 0 && /\b(quais|quantos|agenda|minhas tarefas|meus clientes|quem|onde|como esta)\b/.test(lower));
  if (isConsultOnly && !marcas.some((m) => m.startsWith("recusado:"))) {
    return {
      score: 95,
      grade: "completo",
      hasClient: true,
      hasOutcome: true,
      hasNextStep: true,
      missing: [],
      feedback: "Consulta objetiva ao CRM.",
    };
  }

  const hasClient =
    Boolean(input.hasCompanyId) ||
    gravou.length > 0 ||
    /\b(usina|agro|destilaria| fazenda|grupo|cooperativa|ltda|s\/a|cliente|contato|empresa)\b/.test(lower) ||
    q.split(/\s+/).some((w) => w.length > 3 && /^[A-ZÁÉÍÓÚÂÊÔÃÕÇ]/.test(w));

  const hasOutcome =
    gravou.length > 0 ||
    q.length >= 28 ||
    /\b(visitei|liguei|falei|reuniao|enviei|mandei|apresentei|homolog|orcam|cotac|fechou|perdeu|atendeu|conversamos)\b/.test(
      lower,
    );

  const hasNextStepRefusal = marcas.some(
    (m) => m.includes("proximo_passo") || m.includes("data") || m.includes("prazo"),
  );
  const iaAskedMissingInfo =
    /\b(qual cliente|qual empresa|qual o proximo passo|quando devemos|qual a data|qual o valor|qual o motivo)\b/.test(
      respLower,
    );

  const hasNextStep =
    !hasNextStepRefusal &&
    (gravou.includes("criar_tarefa") ||
      gravou.includes("reagendar_tarefa") ||
      gravou.includes("ganhar_negocio") ||
      gravou.includes("perder_negocio") ||
      /\b(amanha|segunda|terca|quarta|quinta|sexta|semana que vem|dia \d{1,2}|proximo passo|retornar|ligar dia|agendei|retorno)\b/.test(
        lower,
      ) ||
      (gravou.includes("registrar_atividade") && !iaAskedMissingInfo));

  const missing: string[] = [];
  if (!hasClient) missing.push("Não informou o nome do cliente/usina");
  if (!hasOutcome) missing.push("Relato muito curto sem detalhar o que foi tratado");
  if (!hasNextStep) missing.push("Não informou o próximo passo ou data de retorno");

  let score = 100;
  if (!hasClient) score -= 45;
  if (!hasOutcome) score -= 30;
  if (!hasNextStep) score -= 25;
  if (iaAskedMissingInfo && score > 75) score = 72;
  score = Math.max(15, Math.min(100, score));

  const grade: "completo" | "parcial" | "vago" =
    score >= 85 ? "completo" : score >= 55 ? "parcial" : "vago";

  const feedback =
    missing.length === 0
      ? "Pedido completo: informou cliente, desfecho e próximo passo."
      : `Pedido ${grade}: ${missing.join("; ")}.`;

  return {
    score,
    grade,
    hasClient,
    hasOutcome,
    hasNextStep,
    missing,
    feedback,
  };
}

/**
 * Analisa uma execução (run) sob a ótica da IA Avaliadora:
 * separa se a falha foi da IA de Atendimento ou se foi pedido incompleto da equipe,
 * e lê as marcas de auto-correção (`auto_corrigido:...`) e regra aprendida (`regra_aprendida:...`).
 */
export function analyzeRunWithEvaluator(
  run: IaRunAudit,
  companyName?: string,
): EvaluatorAuditReport {
  const order =
    run.orderQuality ??
    evaluateSellerOrderQuality({
      question: run.pergunta,
      hasCompanyId: Boolean(run.companyId),
      gravou: run.gravou,
      marcas: run.marcas,
      resposta: run.resposta,
    });

  const autoHealMark = run.marcas.find((m) => m.startsWith("auto_corrigido:"));
  const autoHealNotified = run.marcas.includes("auto_corrigido_avisado_whatsapp");
  const learnedMark = run.marcas.find((m) => m.startsWith("regra_aprendida:"));
  const autoHealActions = run.marcas
    .filter((m) => m.startsWith("acao_corretora:"))
    .map((m) => m.slice("acao_corretora:".length));

  const autoHealed = Boolean(autoHealMark) || autoHealActions.length > 0;
  const autoHealSummary = autoHealMark ? autoHealMark.slice("auto_corrigido:".length) : undefined;
  const learnedRuleText = learnedMark ? learnedMark.slice("regra_aprendida:".length) : undefined;

  const hasDisconnect =
    run.marcas.some((m) => isDisconnectionMark(m)) ||
    (run.status === "failed" && Boolean(run.errorMessage));

  const userFlaggedError =
    run.marcas.includes("errou") ||
    run.marcas.includes("usuario_marcou_erro") ||
    /^(voce )?(errou|errado|ta errado|esta errado)/i.test(run.pergunta.trim());

  const toolRefused = run.marcas.filter((m) => m.startsWith("recusado:"));
  const hadProblem =
    userFlaggedError ||
    hasDisconnect ||
    run.marcas.includes("comprovante_inventado") ||
    run.marcas.includes("limite_passos") ||
    toolRefused.length > 0;

  if (autoHealed) {
    return {
      rootCause: "erro_ia",
      rootCauseLabel: "Erro da IA corrigido automaticamente pela IA Avaliadora",
      iaErrorDetail:
        userFlaggedError
          ? "O vendedor sinalizou erro na resposta anterior; a IA Avaliadora reprocessou o contexto e gravou a ação correta."
          : "A IA de Atendimento deixou o registro incompleto na 1ª tentativa; a IA Avaliadora completou a gravação no CRM.",
      autoHealed: true,
      autoHealActions: autoHealActions.length > 0 ? autoHealActions : run.gravou,
      autoHealSummary:
        autoHealSummary ||
        `Registro corrigido automaticamente${companyName ? ` em ${companyName}` : ""}.`,
      autoHealNotifiedWhatsapp: autoHealNotified,
      learnedRuleText,
    };
  }

  if (hasDisconnect) {
    return {
      rootCause: "queda_conexao",
      rootCauseLabel: "Instabilidade técnica / Queda de resposta do modelo",
      iaErrorDetail: run.errorMessage || "O modelo demorou ou caiu durante o processamento deste turno.",
      autoHealed: false,
      autoHealActions: [],
      autoHealNotifiedWhatsapp: false,
    };
  }

  // Se recusou porque faltou dado obrigatório que o vendedor não informou (ex.: valor da venda, próximo passo, cliente ambíguo)
  if (toolRefused.length > 0 && order.grade !== "completo") {
    return {
      rootCause: "pedido_incompleto_equipe",
      rootCauseLabel: "Pedido incompleto do vendedor (não é erro da IA)",
      teamIssueDetail:
        order.missing.length > 0
          ? `O vendedor enviou o relato sem: ${order.missing.join(", ")}.`
          : `Faltou informação obrigatória no relato (${toolRefused.map(formatRecordMark).join(", ")}).`,
      autoHealed: false,
      autoHealActions: [],
      autoHealNotifiedWhatsapp: false,
    };
  }

  if (hadProblem) {
    return {
      rootCause: "erro_ia",
      rootCauseLabel: "Falha da IA de Atendimento",
      iaErrorDetail:
        run.marcas
          .filter((m) => isProblemMark(m))
          .map(formatRecordMark)
          .join(" · ") || "A IA não concluiu a gravação esperada para o pedido do vendedor.",
      autoHealed: false,
      autoHealActions: [],
      autoHealNotifiedWhatsapp: false,
      learnedRuleText,
    };
  }

  if (order.grade === "vago" && run.gravou.length === 0) {
    return {
      rootCause: "pedido_incompleto_equipe",
      rootCauseLabel: "Aguardando complemento do vendedor",
      teamIssueDetail: order.feedback,
      autoHealed: false,
      autoHealActions: [],
      autoHealNotifiedWhatsapp: false,
    };
  }

  return {
    rootCause: "ok",
    rootCauseLabel: "Atendimento fluindo normalmente",
    autoHealed: false,
    autoHealActions: [],
    autoHealNotifiedWhatsapp: false,
  };
}

export function classifySessionIntervention(input: {
  runs: IaRunAudit[];
  messages: IaMessageItem[];
  nowMs?: number;
}): {
  level: InterventionLevel;
  reasons: string[];
  reviewedBy?: string;
  errorsCount: number;
  pendingActionsCount: number;
  writesCount: number;
  consultsCount: number;
  iaScorePct: number;
  avgLatencyMs: number;
  conversationState: ConversationClosureState;
  pendingOwner: PendingOwner;
  fluencyScorePct: number;
  turnsPerClosure: number;
  disconnectionsCount: number;
  autoHealedCount: number;
  sellerOrderScorePct: number;
} {
  const nowMs = input.nowMs ?? Date.now();
  const runs = [...input.runs].sort((a, b) => b.at.localeCompare(a.at));
  const messages = [...input.messages].sort((a, b) => a.at.localeCompare(b.at));

  let errorsCount = 0;
  let fallbackCount = 0;
  let writesCount = 0;
  let consultsCount = 0;
  let latencySum = 0;
  let latencyN = 0;
  let disconnectionsCount = 0;
  let autoHealedCount = 0;
  let orderScoreSum = 0;
  let orderScoreN = 0;
  const reasons: string[] = [];
  let reviewedBy: string | undefined;

  for (const r of runs) {
    const asRecord: AgentRecord = {
      id: r.id,
      at: r.at,
      userId: "",
      companyId: r.companyId,
      pergunta: r.pergunta,
      audio: r.audio,
      resposta: r.resposta,
      gravou: r.gravou,
      marcas: r.marcas,
    };
    const res = recordResult(asRecord);
    const isAutoHealed =
      r.marcas.some((m) => m.startsWith("auto_corrigido:")) || Boolean(r.evaluator?.autoHealed);
    if (isAutoHealed) autoHealedCount++;

    if (r.marcas.some((m) => isDisconnectionMark(m)) || (r.status === "failed" && r.errorMessage)) {
      disconnectionsCount++;
    }

    const orderEval =
      r.orderQuality ??
      evaluateSellerOrderQuality({
        question: r.pergunta,
        hasCompanyId: Boolean(r.companyId),
        gravou: r.gravou,
        marcas: r.marcas,
        resposta: r.resposta,
      });
    orderScoreSum += orderEval.score;
    orderScoreN++;

    const evalReport = r.evaluator ?? analyzeRunWithEvaluator(r);
    const hasUnhealedIaError =
      !isAutoHealed &&
      evalReport.rootCause !== "pedido_incompleto_equipe" &&
      (res === "erro" || r.status === "failed" || Boolean(r.errorMessage));

    const revMark = r.marcas.find((m) => m.startsWith("revisado:"));
    if (revMark && !reviewedBy) reviewedBy = revMark.slice("revisado:".length);

    if (hasUnhealedIaError) {
      errorsCount++;
      if (!revMark) {
        for (const m of r.marcas) {
          if (isProblemMark(m)) {
            const label = formatRecordMark(m);
            if (!reasons.includes(label)) reasons.push(label);
          }
        }
        if (r.status === "failed" && r.errorMessage) {
          const msg = `Falha na execução: ${r.errorMessage.slice(0, 80)}`;
          if (!reasons.includes(msg)) reasons.push(msg);
        }
      }
    } else if (r.gravou.length > 0 || isAutoHealed) {
      writesCount += Math.max(1, r.gravou.length);
    } else {
      consultsCount++;
    }

    if (r.caminho === "fluxo_antigo" || r.marcas.includes("fluxo_antigo")) {
      fallbackCount++;
    }
    if (r.latencyMs > 0) {
      latencySum += r.latencyMs;
      latencyN++;
    }
  }

  const lastMsg = messages.at(-1);
  const waitingReply =
    lastMsg?.direction === "in" && nowMs - new Date(lastMsg.at).getTime() > 2 * 60_000;
  if (waitingReply) {
    reasons.push("Última mensagem do vendedor ainda sem resposta da IA");
  }

  const lastOutQuestion =
    lastMsg?.direction === "out" && /\?\s*$/.test(lastMsg.body.trim());
  const pendingActionsCount = messages.filter((m) => m.actionPending).length;
  if (pendingActionsCount > 0) {
    reasons.push(
      pendingActionsCount === 1
        ? "Aguardando vendedor responder CONFIRMAR no WhatsApp"
        : `${pendingActionsCount} ações aguardando confirmação do vendedor`,
    );
  } else if (lastOutQuestion && writesCount === 0) {
    reasons.push("A IA fez uma pergunta para completar o registro e o vendedor ainda não respondeu");
  }

  if (fallbackCount > 0 && reasons.length === 0) {
    reasons.push(
      fallbackCount === 1
        ? "1 atendimento caiu no modo de contingência"
        : `${fallbackCount} atendimentos caíram no modo de contingência`,
    );
  }

  const unresolvedErrors = runs.filter((r) => {
    const rev = r.marcas.some((m) => m.startsWith("revisado:"));
    const healed =
      r.marcas.some((m) => m.startsWith("auto_corrigido:")) || Boolean(r.evaluator?.autoHealed);
    const evalReport = r.evaluator ?? analyzeRunWithEvaluator(r);
    const bad =
      r.status === "failed" ||
      Boolean(r.errorMessage) ||
      r.marcas.some((m) => isProblemMark(m));
    return bad && !rev && !healed && evalReport.rootCause !== "pedido_incompleto_equipe";
  }).length;

  let level: InterventionLevel = "normal";
  if (unresolvedErrors > 0 || waitingReply) {
    level = "intervencao";
  } else if (pendingActionsCount > 0 || fallbackCount > 0 || lastOutQuestion) {
    level = "atencao";
  } else if ((reviewedBy && errorsCount > 0) || autoHealedCount > 0) {
    level = "revisado";
  }

  let pendingOwner: PendingOwner = "nenhuma";
  if (unresolvedErrors > 0 || waitingReply) {
    pendingOwner = "ia";
  } else if (pendingActionsCount > 0 || lastOutQuestion) {
    pendingOwner = "equipe";
  }

  let conversationState: ConversationClosureState = "consulta_concluida";
  if (pendingOwner === "ia") {
    conversationState = "em_aberto_ia";
  } else if (pendingOwner === "equipe") {
    conversationState = "em_aberto_equipe";
  } else if (autoHealedCount > 0) {
    conversationState = "auto_corrigida";
  } else if (writesCount > 0) {
    conversationState = "fechada_com_registro";
  }

  const totalRuns = runs.length;
  const iaScorePct =
    totalRuns > 0 ? Math.max(0, Math.round(((totalRuns - errorsCount) / totalRuns) * 100)) : 100;
  const avgLatencyMs = latencyN > 0 ? Math.round(latencySum / latencyN) : 0;
  const sellerOrderScorePct = orderScoreN > 0 ? Math.round(orderScoreSum / orderScoreN) : 100;

  const totalMsgs = messages.length || totalRuns * 2;
  const closures = Math.max(1, writesCount + consultsCount);
  const turnsPerClosure = Number((totalMsgs / closures).toFixed(1));
  const fluencyPenalty = errorsCount * 18 + fallbackCount * 10 + (pendingActionsCount > 0 ? 8 : 0);
  const fluencyScorePct = Math.max(25, Math.min(100, 100 - fluencyPenalty));

  return {
    level,
    reasons,
    reviewedBy,
    errorsCount,
    pendingActionsCount,
    writesCount,
    consultsCount,
    iaScorePct,
    avgLatencyMs,
    conversationState,
    pendingOwner,
    fluencyScorePct,
    turnsPerClosure,
    disconnectionsCount,
    autoHealedCount,
    sellerOrderScorePct,
  };
}

export function summarizeIaSessions(sessions: IaSessionBlock[]): IaSessionsSummary {
  const totalSessions = sessions.length;
  const activeNow = sessions.filter((s) => s.status === "active").length;
  const needsIntervention = sessions.filter((s) => s.intervention === "intervencao").length;
  const attentionCount = sessions.filter((s) => s.intervention === "atencao").length;
  const messagesFromSeller = sessions.reduce((sum, s) => sum + s.messagesFromSeller, 0);
  const messagesFromIa = sessions.reduce((sum, s) => sum + s.messagesFromIa, 0);
  const totalMessages = sessions.reduce((sum, s) => sum + s.messagesTotal, 0);
  const totalWrites = sessions.reduce((sum, s) => sum + s.writesCount, 0);

  const allRuns = sessions.flatMap((s) => s.runs);
  const totalRuns = allRuns.length;
  const errorRuns = sessions.reduce((sum, s) => sum + s.errorsCount, 0);
  const iaScorePct =
    totalRuns > 0
      ? Math.max(0, Math.round(((totalRuns - errorRuns) / totalRuns) * 100))
      : sessions.length > 0
        ? Math.round(sessions.reduce((sum, s) => sum + s.iaScorePct, 0) / sessions.length)
        : 100;

  const latSessions = sessions.filter((s) => s.avgLatencyMs > 0);
  const avgLatencyMs =
    latSessions.length > 0
      ? Math.round(latSessions.reduce((sum, s) => sum + s.avgLatencyMs, 0) / latSessions.length)
      : 0;

  const closedWithRecordCount = sessions.filter(
    (s) =>
      s.conversationState === "fechada_com_registro" ||
      s.conversationState === "auto_corrigida" ||
      (!s.conversationState && s.writesCount > 0 && s.intervention !== "intervencao"),
  ).length;
  const openConversationsCount = sessions.filter(
    (s) =>
      s.conversationState === "em_aberto_equipe" ||
      s.conversationState === "em_aberto_ia" ||
      s.intervention === "intervencao" ||
      s.intervention === "atencao",
  ).length;

  const iaPendingCount = sessions.filter(
    (s) => s.pendingOwner === "ia" || s.intervention === "intervencao",
  ).length;
  const teamPendingCount = sessions.filter(
    (s) => s.pendingOwner === "equipe" || (s.intervention === "atencao" && s.pendingActionsCount > 0),
  ).length;

  const autoHealedCount = sessions.reduce((sum, s) => sum + (s.autoHealedCount ?? 0), 0);
  const disconnectionsCount = sessions.reduce((sum, s) => sum + (s.disconnectionsCount ?? 0), 0);
  const teamOrderIssuesCount = sessions.reduce(
    (sum, s) => sum + (s.badOrderExamples?.length ?? 0),
    0,
  );

  const fluencyScorePct =
    sessions.length > 0
      ? Math.round(
          sessions.reduce((sum, s) => sum + (s.fluencyScorePct ?? s.iaScorePct), 0) /
            sessions.length,
        )
      : 100;

  const teamOrderQualityPct =
    sessions.length > 0
      ? Math.round(
          sessions.reduce((sum, s) => sum + (s.sellerOrderScorePct ?? 88), 0) / sessions.length,
        )
      : 100;

  return {
    totalSessions,
    activeNow,
    needsIntervention,
    attentionCount,
    totalMessages,
    messagesFromSeller,
    messagesFromIa,
    totalWrites,
    iaScorePct,
    avgLatencyMs,
    closedWithRecordCount,
    openConversationsCount,
    iaPendingCount,
    teamPendingCount,
    iaErrorsCount: errorRuns,
    teamOrderIssuesCount,
    autoHealedCount,
    fluencyScorePct,
    disconnectionsCount,
    teamOrderQualityPct,
  };
}

